/**
 * Emit a Tailwind v4 theme stylesheet from the DTCG source of truth, so Tailwind
 * consumers (thornberry and apps) read the same tokens as the Panda preset and
 * the Rust crate. This is what lets Tailwind be the canonical engine without
 * abandoning the design system: `bg-brand`, `rounded-lg`, `text-fg-default`
 * resolve to real tokens, and a hardcoded `#hex` becomes a visible deviation.
 *
 * Output (`src/tailwind.css`):
 * - `@theme` with the primitive scales (colors, radii, spacing, type, ...), so
 *   Tailwind generates the utilities.
 * - `:root` / `.dark` custom properties for the semantic (themed) colors, wired
 *   into `@theme inline` so `bg-canvas`/`text-fg-default`/etc. switch with the
 *   active theme.
 */

import primitivesDoc from "../dtcg/primitives.tokens.json";
import { resolve } from "../lib/resolve";

type Node = { $value?: unknown } & Record<string, unknown>;

const isLeaf = (n: unknown): n is Node =>
  !!n && typeof n === "object" && "$value" in (n as object);

/** Flatten a primitive scale to `[dashKey, cssValue]`, dropping DEFAULT suffixes. */
const flatten = (node: unknown, path: string[] = []): [string, string][] => {
  if (isLeaf(node)) {
    const key = path.filter((p) => p !== "DEFAULT").join("-");
    const v = node.$value;
    const value = Array.isArray(v) ? v.join(", ") : String(v);
    return [[key, value]];
  }
  if (node && typeof node === "object") {
    return Object.entries(node as Record<string, unknown>).flatMap(([k, v]) =>
      flatten(v, [...path, k]),
    );
  }
  return [];
};

/** Resolve every color leaf to a concrete value, keyed by its Tailwind name. */
const colorVars = (): [string, string][] => {
  const out: [string, string][] = [];
  const walk = (node: unknown, path: string[]) => {
    if (isLeaf(node)) {
      const key = path.filter((p) => p !== "DEFAULT").join("-");
      out.push([key, resolve(path.join("."), "base")]);
      return;
    }
    if (node && typeof node === "object") {
      for (const [k, v] of Object.entries(node as Record<string, unknown>)) {
        walk(v, [...path, k]);
      }
    }
  };
  walk(primitivesDoc.colors, []);
  return out;
};

// Primitive scales mapped to their Tailwind v4 `@theme` namespace.
const SCALE_NS: Record<string, string> = {
  radii: "radius",
  spacing: "spacing",
  fontSizes: "text",
  fontWeights: "font-weight",
  letterSpacings: "tracking",
  lineHeights: "leading",
  fonts: "font",
  blurs: "blur",
  easings: "ease",
};

// Curated semantic color roles -> Tailwind color name -> DTCG semantic path.
const SEMANTIC: Record<string, string> = {
  "bg-canvas": "background.canvas",
  "bg-default": "background.default",
  "bg-subtle": "background.subtle",
  "bg-muted": "background.muted",
  "bg-emphasized": "background.emphasized",
  "fg-default": "foreground.default",
  "fg-muted": "foreground.muted",
  "fg-subtle": "foreground.subtle",
  accent: "accent.default",
  "accent-emphasized": "accent.emphasized",
  "accent-fg": "accent.foreground",
  "border-default": "border.default",
  "border-muted": "border.muted",
  "border-subtle": "border.subtle",
};

const docScales = primitivesDoc as unknown as Record<string, unknown>;

const themeLines = [
  ...colorVars().map(([k, v]) => `  --color-${k}: ${v};`),
  ...Object.entries(SCALE_NS).flatMap(([scale, ns]) =>
    flatten(docScales[scale]).map(([k, v]) => `  --${ns}-${k}: ${v};`),
  ),
].join("\n");

const rootLines = Object.entries(SEMANTIC)
  .map(([name, path]) => `  --sigil-${name}: ${resolve(path, "base")};`)
  .join("\n");

const darkLines = Object.entries(SEMANTIC)
  .map(([name, path]) => `  --sigil-${name}: ${resolve(path, "dark")};`)
  .join("\n");

const inlineLines = Object.keys(SEMANTIC)
  .map((name) => `  --color-${name}: var(--sigil-${name});`)
  .join("\n");

const css = `/*
 * Generated by \`bun emit-tailwind\` from the DTCG token source of truth
 * (src/dtcg/*.tokens.json). DO NOT EDIT.
 *
 * Usage: \`@import "@omnidotdev/sigil-tokens/tailwind.css";\` in a Tailwind v4
 * stylesheet. Primitive scales generate utilities directly; the semantic
 * colors (bg-*, fg-*, accent*, border-*) switch with the \`.dark\` class.
 */
@theme {
${themeLines}
}

:root {
${rootLines}
}

.dark {
${darkLines}
}

@theme inline {
${inlineLines}
}
`;

const emit = async () => {
  // Sanity-check the same chains the Rust emitter checks.
  const checks: [string, "base" | "dark", string][] = [
    ["accent.default", "dark", "#02cac5"],
    ["background.canvas", "dark", "#0a0a0a"],
    ["background.default", "base", "#ffffff"],
  ];
  for (const [path, mode, want] of checks) {
    const got = resolve(path, mode);
    if (got !== want) {
      throw new Error(`resolve(${path}, ${mode}) = ${got}, expected ${want}`);
    }
  }

  const out = `${process.cwd()}/src/tailwind.css`;
  await Bun.write(out, css);
  console.info(`✅ wrote ${out}`);
};

emit().catch((err) => {
  console.error(err);
  process.exit(1);
});
